"""RFQ arrival flow generator (spec.md §2, "RFQ flow data").

No public dataset of retail RFQ arrivals exists, so this whole module is a
documented, parameterised proxy: a non-homogeneous Poisson arrival process
per instrument (generated by thinning — Lewis-Shedler), log-normal ticket
sizes, a 50/50-by-default direction split, an informed-fraction label per
request, and a synthetic requester population that includes a small
high-frequency "abusive" minority for exercising compliance/surveillance
(§12) later.

Exemption status (§5(2)) is deliberately *not* set here — that requires
venue-rulebook knowledge this module doesn't have. Every RFQ is emitted
with is_exempt=False; venue/obligations.py evaluates and replaces each RFQ
before it reaches the quoter.
"""

from __future__ import annotations

import hashlib
import math
from dataclasses import dataclass
from datetime import date, datetime, timedelta

from numpy.random import Generator, default_rng

from rfq_mm.core.clock import SessionCalendar
from rfq_mm.core.types import RFQ, Side


def _isin_flow_rng(seed: int, isin: str, d: date) -> Generator:
    digest = hashlib.sha256(f"flow|{isin}|{d.isoformat()}".encode()).digest()
    salt = int.from_bytes(digest[:8], "little")
    return default_rng([seed, salt & 0xFFFFFFFF, (salt >> 32) & 0xFFFFFFFF])


@dataclass(frozen=True, slots=True)
class FlowParams:
    seed: int
    base_lambda_per_hour: float = 40.0
    u_shape_amplitude: float = 1.0
    us_open_bump_center_minutes_from_open: float = 450.0  # 08:00 + 7h30m = 15:30 CET
    us_open_bump_amplitude: float = 1.5
    us_open_bump_width_minutes: float = 30.0
    size_median_eur: float = 300.0
    size_sigma: float = 1.3
    min_size_eur: float = 10.0
    buy_probability: float = 0.5
    informed_fraction: float = 0.1
    n_requesters: int = 500
    abuser_fraction: float = 0.02
    abuser_rate_multiplier: float = 25.0


@dataclass(frozen=True, slots=True)
class FlowResult:
    rfqs: list[RFQ]
    abuser_requester_ids: frozenset[str]


def _intensity_per_hour(x: float, minutes_since_open: float, p: FlowParams) -> float:
    """lambda(t) in requests/hour: U-shaped session profile + Gaussian bump at
    15:30 CET (US open), per R104-R105."""
    base = p.base_lambda_per_hour * (1.0 + p.u_shape_amplitude * (2.0 * x - 1.0) ** 2)
    bump = p.base_lambda_per_hour * p.us_open_bump_amplitude * math.exp(
        -0.5
        * (
            (minutes_since_open - p.us_open_bump_center_minutes_from_open)
            / p.us_open_bump_width_minutes
        )
        ** 2
    )
    return base + bump


def _lambda_max(p: FlowParams) -> float:
    """A safe (if slightly loose) upper bound on lambda(t) over the session,
    for Lewis-Shedler thinning: sum of the two terms' individual peaks."""
    return p.base_lambda_per_hour * (1.0 + p.u_shape_amplitude) + (
        p.base_lambda_per_hour * p.us_open_bump_amplitude
    )


def _thinned_arrivals(
    session: SessionCalendar, d: date, rng: Generator, p: FlowParams
) -> list[datetime]:
    start = session.session_open(d)
    end = session.session_close(d)
    session_minutes = (end - start).total_seconds() / 60.0
    lam_max = _lambda_max(p)

    arrivals: list[datetime] = []
    t_minutes = 0.0
    while True:
        u1 = rng.random()
        t_minutes += (-math.log(u1) / lam_max) * 60.0
        if t_minutes >= session_minutes:
            break
        x = t_minutes / session_minutes
        lam = _intensity_per_hour(x, t_minutes, p)
        u2 = rng.random()
        if u2 <= lam / lam_max:
            arrivals.append(start + timedelta(minutes=t_minutes))
    return arrivals


def _build_requester_pool(p: FlowParams, rng: Generator) -> tuple[list[str], list[float], set[int]]:
    n_abusers = max(1, round(p.n_requesters * p.abuser_fraction))
    requester_ids = [f"req-{i:05d}" for i in range(p.n_requesters)]
    weights = [1.0] * p.n_requesters
    abuser_idx = set(rng.choice(p.n_requesters, size=n_abusers, replace=False).tolist())
    for i in abuser_idx:
        weights[i] = p.abuser_rate_multiplier
    total = sum(weights)
    weights = [w / total for w in weights]
    return requester_ids, weights, abuser_idx


def generate_rfqs(
    session: SessionCalendar, d: date, isins: list[str], params: FlowParams
) -> FlowResult:
    pool_rng = default_rng([params.seed, 0xF10])
    requester_ids, weights, abuser_idx = _build_requester_pool(params, pool_rng)
    abuser_ids = frozenset(requester_ids[i] for i in abuser_idx)

    all_rfqs: list[RFQ] = []
    seq = 0
    for isin in isins:
        rng = _isin_flow_rng(params.seed, isin, d)
        for ts in _thinned_arrivals(session, d, rng, params):
            side = Side.BUY if rng.random() < params.buy_probability else Side.SELL
            size = float(
                rng.lognormal(mean=math.log(params.size_median_eur), sigma=params.size_sigma)
            )
            size = max(size, params.min_size_eur)
            is_informed = rng.random() < params.informed_fraction
            requester_id = requester_ids[rng.choice(len(requester_ids), p=weights)]
            seq += 1
            all_rfqs.append(
                RFQ(
                    rfq_id=f"rfq-{d.isoformat()}-{seq:06d}",
                    ts=ts,
                    isin=isin,
                    requester_id=requester_id,
                    side=side,
                    requested_size_eur=size,
                    is_exempt=False,
                    is_informed=is_informed,
                )
            )

    all_rfqs.sort(key=lambda r: r.ts)
    return FlowResult(rfqs=all_rfqs, abuser_requester_ids=abuser_ids)
